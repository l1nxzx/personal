const DAY_MS = 86_400_000;

/** The question for a local date (`YYYY-MM-DD`): consecutive days get consecutive questions. */
export function promptFor(date: string): string {
  const [y, m, d] = date.split('-').map(Number);
  const day = Math.floor(Date.UTC(y!, m! - 1, d!) / DAY_MS);
  return PROMPTS[((day % PROMPTS.length) + PROMPTS.length) % PROMPTS.length]!;
}
